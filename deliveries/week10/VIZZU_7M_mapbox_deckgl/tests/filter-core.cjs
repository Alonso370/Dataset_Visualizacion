const assert = require('node:assert/strict');
const {inside,series,hourMatches,validHour,validWeekday} = require('../js/filter-core.js');
const all = new Set(Array.from({length:24},(_,hour) => hour));
const rows = [{hour:23,weekday:4},{hour:0,weekday:5},{hour:0,weekday:6},{hour:12,weekday:0},{hour:null,weekday:1},{hour:6,weekday:null}];
assert.equal(validHour(24),false); assert.equal(validHour(0),true); assert.equal(validHour(null),false);
assert.equal(validWeekday(7),false); assert.equal(validWeekday(6),true);
const counts = series(rows,all);
assert.equal(counts.weekday[23].n,1,'Friday belongs to weekdays');
assert.equal(counts.weekend[0].n,2,'Saturday and Sunday belong to weekends');
assert.equal(counts.missing,2,'Missing fields must not fabricate midnight or Monday');
const overnight = new Set([23,0]);
assert.equal(hourMatches(rows[0],overnight),true); assert.equal(hourMatches(rows[3],overnight),false);
assert.equal(hourMatches(rows[4],all),true); assert.equal(hourMatches(rows[4],overnight),false);
assert.equal(hourMatches(rows[0],new Set()),false);
const square = [[0,0],[4,0],[4,4],[0,4]];
assert.equal(inside(square,[2,2]),true); assert.equal(inside(square,[4,2]),true); assert.equal(inside(square,[5,2]),false);
const concave = [[0,0],[4,0],[4,4],[2,2],[0,4]];
assert.equal(inside(concave,[2,3]),false,'Concave lasso must not silently become a bounding box or convex hull');
assert.equal(inside(concave,[1,1]),true);
console.log('OK: weekdays/weekends, hours, midnight, missing values, boundary and concave lasso.');
